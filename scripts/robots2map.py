#!/usr/bin/env python3
"""Turn a robots.txt into an nginx map include for pow_gate_decision.

Every User-agent group that disallows the whole site ("Disallow: /") becomes
one map entry, so crawlers you already ask to stay away are refused when they
ignore the request. The "*" group is skipped: it describes everyone.

    ./scripts/robots2map.py robots.txt > /etc/nginx/pow-rules/robots.map
    ./scripts/robots2map.py --action challenge:500000 https://example.com/robots.txt

Include the result inside the map that produces your decision variable.
"""
import argparse
import re
import sys
import urllib.request


def groups(text):
    """Yield (agents, rules) per group; rules are (field, value) pairs."""
    agents, rules = [], []
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if ':' not in line:
            continue
        field, value = (part.strip() for part in line.split(':', 1))
        field = field.lower()
        if field == 'user-agent':
            if rules:
                yield agents, rules
                agents, rules = [], []
            agents.append(value)
        elif agents:
            rules.append((field, value))
    if agents:
        yield agents, rules


def blocked_agents(text):
    seen = []
    for agents, rules in groups(text):
        if not any(field == 'disallow' and value == '/' for field, value in rules):
            continue
        # An explicit "Allow: /" in the same group takes the block back.
        if any(field == 'allow' and value == '/' for field, value in rules):
            continue
        for agent in agents:
            if agent != '*' and agent.lower() not in (name.lower() for name in seen):
                seen.append(agent)
    return seen


def map_key(agent):
    # nginx map keys end at whitespace or ';' and treat '$', quotes and braces
    # specially, so escape everything that is not a plain word character.
    return '~*' + re.sub(r'([^A-Za-z0-9_-])', r'\\\1', agent)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('source', help='robots.txt path, http(s) URL, or - for stdin')
    parser.add_argument('--action', default='deny',
                        help='decision for the listed agents (default: deny)')
    args = parser.parse_args()
    if not re.fullmatch(r'allow|deny(:\d{3})?|challenge(:[a-z0-9:]+)?|verify:[A-Za-z0-9_]+', args.action):
        parser.error(f'not a pow_gate_decision value: {args.action}')
    if args.source == '-':
        text = sys.stdin.read()
    elif re.match(r'https?://', args.source):
        request = urllib.request.Request(args.source, headers={'User-Agent': 'robots2map'})
        with urllib.request.urlopen(request, timeout=15) as response:
            text = response.read(1 << 20).decode('utf-8', 'replace')
    else:
        with open(args.source, encoding='utf-8', errors='replace') as handle:
            text = handle.read()
    agents = blocked_agents(text)
    print(f'# Generated by robots2map.py from {args.source}: {len(agents)} agent(s) with "Disallow: /".')
    width = max((len(map_key(agent)) for agent in agents), default=0)
    for agent in agents:
        print(f'{map_key(agent):<{width}}  {args.action};')


if __name__ == '__main__':
    main()
